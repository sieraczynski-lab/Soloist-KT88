from schwired import WiredSch
from boards import kanal

def build():
    b = kanal()
    S = WiredSch(b, ("A3", 16535, 11693))
    P, W, L = S.put, S.w, S.lab
    # ---------------- input ----------------
    P("J101", "PAD_L", 1000, 2950); P("C101", "CH", 1450, 2950); P("R101", "R", 1750, 3250); P("R102", "RH", 2150, 2950)
    P("J102", "PAD_L", 1000, 3600)
    W(("J101", 1), ("C101", 1)); W(("C101", 2), (1750, 2950), ("R102", 1)); W((1750, 2950), ("R101", 1))
    L(("R101", 2), "GND", 3, stub=(0, 100)); L(("J102", 1), "GND", 0, stub=(100, 0))
    # ---------------- EF86 ----------------
    P("V101", "EF86W", 2800, 3000)
    W(("R102", 2), ("V101", 9))
    W(("V101", 2), (2600, 3500), (2800, 3500), ("V101", 7)); W(("V101", 3), (2700, 3500)); W((2700, 3500), (2700, 3700))
    W(("V101", 8), (2350, 3050), (2350, 3700), (3700, 3700))
    P("R103", "R", 2350, 3950); W((2350, 3700), ("R103", 1)); L(("R103", 2), "GND", 3, stub=(0, 100))
    P("R104", "RH", 2700, 4000); P("C103", "CH", 2700, 4250); P("J103", "PAD", 3150, 4000)
    W((2550, 3700), ("R104", 1)); W(("R104", 1), ("C103", 1)); W(("R104", 2), ("C103", 2)); W(("R104", 2), ("J103", 1))
    P("TP109", "TP_D", 3200, 3850)
    # screen grid
    P("R106", "R", 3700, 2550); P("C102", "C", 3700, 3250); P("R107", "R", 3950, 3150)
    W(("V101", 1), (3700, 2850)); W(("R106", 2), (3700, 2850), ("C102", 1)); W(("C102", 2), (3700, 3700))
    W((3700, 2850), (3950, 2850), ("R107", 1)); L(("R107", 2), "GND", 3, stub=(0, 100))
    L(("R106", 1), "B+1", 1, stub=(0, -100))
    L(("V101", 4), "HTR_A", 0, stub=(100, 0)); L(("V101", 5), "HTR_B", 0, stub=(100, 0))
    # anode
    P("R105", "R", 2600, 2050); L(("R105", 1), "B+1", 1, stub=(0, -100))
    W(("V101", 6), (2800, 2200), (2800, 1600), (6050, 1600)); W(("R105", 2), (2800, 2200))
    P("R128", "R", 3150, 1750); P("C107", "C", 3150, 2100); W(("R128", 2), ("C107", 1))
    L(("C107", 2), "GND", 3, stub=(0, 100))
    P("TP108", "TP", 3500, 1450)
    # ---------------- LTP ----------------
    P("V102", "E88CCW", 5000, 3000)
    P("R108", "RH", 4250, 3000); W((4100, 1600), ("R108", 1)); W(("R108", 2), ("V102", 2))
    L(("V102", 9), "GND", 2, stub=(-100, 0))
    L(("V102", 4), "HTR_A", 0, stub=(100, 0)); L(("V102", 5), "HTR_B", 0, stub=(100, 0))
    P("R111", "R", 4850, 2150); P("R112", "R", 5150, 2150)
    L(("R111", 1), "B+2", 1, stub=(0, -100)); L(("R112", 1), "B+2", 1, stub=(0, -100))
    W(("R111", 2), ("V102", 1)); W(("R112", 2), ("V102", 6))
    # options R129 / C108
    P("R129", "R", 5550, 1750); P("C108", "C", 5550, 2100); W(("R129", 2), ("C108", 1)); W(("C108", 2), (5550, 2350))
    # anode lines
    W((5150, 2350), (6550, 2350))                 # ANODE_B
    W((4850, 2500), (6400, 2500), (6400, 4100))   # ANODE_A
    P("TP105", "TP", 6250, 2200); P("TP104", "TP_D", 6200, 2650)
    # second grid + N_GB
    P("R110", "RH", 5700, 3000); W(("V102", 7), ("R110", 1))
    P("R109", "R", 6050, 1750); W(("R109", 2), (6050, 3000)); W(("R110", 2), (6050, 3000), (6250, 3000))
    P("C104", "C", 6250, 3300); W((6250, 3000), ("C104", 1)); L(("C104", 2), "GND", 3, stub=(0, 100))
    # ---------------- CCS ----------------
    W(("V102", 3), (4850, 3550), (5250, 3550)); W(("V102", 8), (5150, 3550))
    P("TP103", "TP", 5250, 3400)
    P("Q101", "DN2540W", 5000, 4000); W((5000, 3550), ("Q101", 2))
    P("R113", "R", 4450, 4300); W(("Q101", 1), (4700, 4000)); W((4700, 4000), (4450, 4000), ("R113", 1))
    L(("R113", 2), "GND", 3, stub=(0, 100))
    P("D105", "ZENER_H", 4850, 4450); W((4700, 4000), ("D105", 2)); W(("Q101", 3), ("D105", 1))
    P("P101", "POT", 5000, 4750); W(("D105", 1), ("P101", 1))
    W(("P101", 2), (5150, 4900), ("P101", 3))
    P("R114", "R", 5000, 5050); L(("R114", 2), "GND", 3, stub=(0, 100))
    # ---------------- coupling + bias top ----------------
    P("C105", "CHR", 6700, 2350); P("J107", "PAD", 7450, 2350)
    W(("C105", 1), ("J107", 1))
    P("R115", "R", 7100, 2100); W(("R115", 2), (7100, 2350))
    P("R119", "R", 7100, 1700); W(("R119", 2), ("R115", 1))
    L(("R119", 1), "VBIAS", 1, stub=(0, -100))
    P("P102", "POT", 7800, 2000); W(("R119", 2), ("P102", 1)); W(("P102", 2), (7950, 2150), ("P102", 3))
    P("R121", "R", 7800, 2300); L(("R121", 2), "GND", 3, stub=(0, 100))
    P("TP106", "TP", 7450, 1700)
    # ---------------- coupling + bias bottom ----------------
    P("C106", "CHR", 6700, 4100); W((6400, 4100), ("C106", 2)); P("J108", "PAD", 7450, 4100)
    W(("C106", 1), ("J108", 1))
    P("R116", "R", 7100, 3850); W(("R116", 2), (7100, 4100))
    P("R120", "R", 7100, 3450); W(("R120", 2), ("R116", 1))
    L(("R120", 1), "VBIAS", 1, stub=(0, -100))
    P("P103", "POT", 7800, 3750); W(("R120", 2), ("P103", 1)); W(("P103", 2), (7950, 3900), ("P103", 3))
    P("R122", "R", 7800, 4050); L(("R122", 2), "GND", 3, stub=(0, 100))
    P("TP107", "TP", 7450, 3450)
    P("J106", "PAD", 7450, 1450); W(("J106", 1), (7100, 1450))
    # ---------------- power ----------------
    P("J104", "PAD_L", 1000, 5300); P("R130", "RH", 1450, 5300); W(("J104", 1), ("R130", 1))
    P("C130", "CP", 1800, 5550); P("R131", "RH", 2250, 5300); P("C131", "CP", 2700, 5550)
    W(("R130", 2), (1800, 5300), ("R131", 1)); W((1800, 5300), ("C130", 1))
    W(("R131", 2), (2700, 5300), (2950, 5300)); W((2700, 5300), ("C131", 1))
    L((1800, 5300), "B+2", 1, stub=(0, -100)); L((2700, 5300), "B+1", 1, stub=(0, -100))
    L(("C130", 2), "GND", 3, stub=(0, 100)); L(("C131", 2), "GND", 3, stub=(0, 100))
    P("TP102", "TP", 2000, 5150); P("TP101", "TP", 2950, 5150)
    P("J105", "PAD_L", 1000, 5900); L(("J105", 1), "GND", 0, stub=(100, 0))
    P("J109", "PAD_L", 1000, 6300); L(("J109", 1), "HTR_A", 0, stub=(100, 0))
    P("J110", "PAD_L", 1000, 6550); L(("J110", 1), "HTR_B", 0, stub=(100, 0))
    # notes
    for x, y, t in ((900, 2650, "WEJSCIE"), (2250, 1250, "EF86 - stopien wejsciowy"), (4300, 1250, "E88CC - odwracacz fazy (LTP)"),
                    (4300, 5500, "Zrodlo pradowe ogona 14 mA"), (6600, 1250, "Sprzeganie i bias KT88"),
                    (900, 4950, "Zasilanie kanalu"), (900, 6050, "Zarzenie / masa"),
                    (6600, 4600, "J107 -> R117 -> siatka V103"), (6600, 4720, "J108 -> R118 -> siatka V104"),
                    (2400, 4600, "J103 FB <- wyjscie 4 ohm"), (900, 7200, "Opcje (niemontowane): R128/C107 siec schodkowa, R129/C108 korekcja fazy")):
        S.note(x, y, t, 60)
    S.autolabel()
    return S

if __name__ == "__main__":
    S = build()
    for e in S.verify():
        print(e)
    print("ok", len(S.segs), "segments")
