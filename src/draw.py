def amp():
    s = Sheet(1640, 840, "Schemat jednego kanału")

    # ---- input ----
    s.term(50, 482, "WE", "end")
    s.wire((50, 482), (85, 482))
    s.caph(85, 130, 482, "C101", "47n/250V")
    s.wire((130, 482), (160, 482)); s.dot(160, 482)
    s.resv(160, 482, 600, "R101", "220k"); s.gnd(160, 600)
    s.resh(160, 245, 482, "R102", "1k", side="b")
    # ---- EF86 ----
    v1 = s.pentode(330, 470, "V101", "EF86")
    s.wire((245, 482), v1["g1"])
    s.wire(v1["g3"], (262, 454), (262, 560), (330, 560))
    s.wire(v1["k"], (330, 560)); s.dot(330, 560)
    s.volt(338, 545, "0,8 V")
    s.resv(330, 560, 650, "R103", "330R", side="l"); s.gnd(330, 650)
    s.wire((330, 560), (450, 560)); s.dot(400, 560)
    # feedback network
    s.wire((400, 560), (400, 700)); s.dot(400, 700)
    s.resh(400, 480, 700, "R104", "27k*")
    s.wire((400, 700), (400, 745)); s.caph(400, 480, 745, "C103", "120p*", side="b")
    s.wire((480, 745), (480, 700)); s.dot(480, 700)
    s.wire((480, 700), (520, 700)); s.flag(520, 700, "FB", "right")
    s.text(520, 724, "z wyjścia 4 Ω", "note")
    # screen grid
    s.wire(v1["g2"], (450, v1["g2"][1])); s.dot(450, 468)
    s.volt(386, 458, "73 V")
    s.resv(450, 395, 468, "R106", "470k"); s.flag(450, 395, "B+1")
    s.capv(450, 468, 560, "C102", "47n/400V", side="l")
    s.wire((450, 468), (510, 468))
    s.resv(510, 468, 590, "R107", "1M5"); s.gnd(510, 590)
    # anode
    s.wire(v1["a"], (330, 330)); s.dot(330, 330)
    s.resv(330, 225, 330, "R105", "100k 1W"); s.flag(330, 225, "B+1 290 V")
    s.volt(338, 350, "81 V")
    s.wire((330, 330), (600, 330), (600, 400)); s.dot(600, 400)
    # ---- LTP E88CC ----
    va = s.triode(720, 400, "V102a", "E88CC", gside=-1, lab=(-112, 52))
    vb = s.triode(900, 400, "V102b", "E88CC", gside=1, lab=(150, 52))
    s.resh(600, 680, 400, "R108", "1k")
    # R109 1M from EF86 anode to grid of V102b (return path below)
    s.wire((600, 400), (600, 790), (765, 790))
    s.resh(765, 845, 790, "R109", "1M", side="b")
    s.wire((845, 790), (1010, 790), (1010, 400))
    s.resh(940, 1010, 400, "R110", "1k"); s.dot(1010, 400)
    s.wire((1010, 400), (1050, 400), (1050, 412))
    s.capv(1050, 412, 470, "C104", "470n/400V"); s.gnd(1050, 470)
    # anodes
    s.resv(720, 190, 290, "R111", "27k 5W", side="l"); s.flag(720, 190, "B+2 460 V")
    s.resv(900, 190, 315, "R112", "27k 5W", side="r"); s.flag(900, 190, "B+2")
    s.wire((720, 290), va["a"]); s.dot(720, 290)
    s.wire((900, 315), vb["a"]); s.dot(900, 315)
    s.volt(728, 345, "271 V"); s.volt(892, 345, "271 V", "end")
    # cathodes + CCS
    s.wire(va["k"], (720, 480), (900, 480), vb["k"]); s.dot(810, 480)
    s.volt(818, 498, "87 V")
    s.wire((810, 480), (810, 505))
    s.box(785, 505, 50, 50, "", ())
    s.text(810, 535, "CCS", "tiny", "middle")
    s.text(840, 518, "Q101 DN2540", "ref")
    s.text(840, 533, "14 mA", "hv")
    s.wire((785, 530), (760, 530)); s.resv(760, 530, 660, "R113", "1k", side="l"); s.gnd(760, 660)
    s.dot(760, 563); s.dot(810, 563); s.zener(760, 563, 810, 563)
    s.text(783, 626, "D105", "ref", "middle"); s.text(783, 639, "12 V", "val", "middle")
    s.potv(810, 555, 625, "P101", "200R")
    s.resv(810, 625, 700, "R114", "100R"); s.gnd(810, 700)
    # ---- to output stage ----
    # B (right anode) -> upper KT88 ; A (left anode) -> lower KT88
    s.wire((900, 315), (1060, 315), (1060, 262), (1105, 262))
    s.wire((720, 290), (1085, 290), (1085, 608), (1105, 608))
    s.hop(900, 290); s.hop(1060, 290)
    s.caph(1105, 1145, 262, "C105", "0,47µ/630V")
    s.caph(1105, 1145, 608, "C106", "0,47µ/630V", side="b")
    s.wire((1145, 262), (1160, 262)); s.dot(1160, 262)
    s.wire((1145, 608), (1160, 608)); s.dot(1160, 608)
    # bias top
    s.resv(1160, 170, 262, "R115", "100k")
    s.dot(1160, 170)
    s.resv(1160, 92, 170, "R119", "27k"); s.flag(1160, 92, "≈ −80 V")
    s.poth(1095, 1160, 170, "P102", "50k")
    s.resh(1035, 1095, 170, "R121", "27k"); s.gnd(1035, 170)
    # bias bottom
    s.resv(1160, 608, 700, "R116", "100k")
    s.dot(1160, 700)
    s.resv(1160, 700, 790, "R120", "27k"); s.flag(1160, 790, "≈ −80 V", "down")
    s.poth(1095, 1160, 700, "P103", "50k", side="b")
    s.resh(1035, 1095, 700, "R122", "27k", side="b"); s.gnd(1035, 700)
    # ---- KT88 ----
    v3 = s.beam(1300, 250, "V103", "KT88")
    v4 = s.beam(1300, 620, "V104", "KT88", flip=True)
    s.resh(1160, v3["g1"][0], 262, "R117", "4k7")
    s.resh(1160, v4["g1"][0], 608, "R118", "4k7", side="b")
    s.volt(1206, 284, "−48 V", "middle"); s.volt(1206, 594, "−48 V", "middle")
    # cathodes
    s.wire(v3["k"], (1300, 320)); s.dot(1300, 320)
    s.resv(1300, 320, 392, "R125", "10R 1%", side="l"); s.gnd(1300, 392)
    s.wire((1300, 320), (1330, 320)); s.text(1335, 324, "I<tspan baseline-shift=\"sub\" font-size=\"9\">K</tspan> → ADC", "note")
    s.wire(v4["k"], (1300, 540)); s.dot(1300, 540)
    s.resh(1300, 1380, 540, "R126", "10R 1%"); s.gnd(1380, 540)
    s.wire((1300, 540), (1300, 520)); s.text(1294, 516, "I<tspan baseline-shift=\"sub\" font-size=\"9\">K</tspan> → ADC", "note", "end")
    s.volt(1308, 340, "0,55 V"); s.volt(1308, 562, "0,55 V")
    # ---- output transformer ----
    X = 1440
    s.coil_v(X, 150, 700, 25, 1)
    s.add(f'<line class="core" x1="{X+20}" y1="230" x2="{X+20}" y2="620"/>')
    s.add(f'<line class="core" x1="{X+26}" y1="230" x2="{X+26}" y2="620"/>')
    s.wire(v3["a"], (1300, 150), (X, 150))
    s.wire(v4["a"], (1300, 700), (X, 700))
    s.resh(v3["g2"][0], X, v3["g2"][1], "R123", "270R 2W")
    s.resh(v4["g2"][0], X, v4["g2"][1], "R124", "270R 2W", side="b")
    s.volt(1308, 180, "463 V")
    s.wire((X, 435), (1400, 435)); s.flag(1400, 435, "B+3 465 V", "left")
    s.text(X + 30, 112, "T101  TTG-KT88PP", "tref", "middle")
    s.text(X + 30, 128, "4 kΩ, odczepy UL 43%", "ttyp", "middle")
    s.text(X - 10, 425, "CT", "tiny", "end")
    # secondary
    S = 1486
    s.coil_v(S, 330, 540, 10, -1)
    s.wire((S, 330), (1560, 330)); s.term(1560, 330, "8 Ω (nc)")
    s.wire((S, 435), (1530, 435)); s.dot(1530, 435); s.wire((1530, 435), (1560, 435)); s.term(1560, 435, "+ 4 Ω")
    s.wire((S, 540), (1530, 540)); s.dot(1530, 540); s.wire((1530, 540), (1560, 540)); s.term(1560, 540, "COM")
    s.resv(1530, 435, 540, None, None)
    s.text(1541, 484, "R127", "ref"); s.text(1541, 497, "100R 2W", "val")
    s.gnd(1530, 540, 22)
    s.wire((1530, 435), (1530, 395)); s.flag(1530, 395, "FB")
    return s.svg()


